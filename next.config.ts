import type { NextConfig } from 'next';

const supabaseHost = (() => {
  try {
    return new URL(process.env.NEXT_PUBLIC_SUPABASE_URL ?? '').hostname;
  } catch {
    return '';
  }
})();

const nextConfig: NextConfig = {
  poweredByHeader: false,
  reactStrictMode: true,
  images: {
    formats: ['image/avif', 'image/webp'],
    remotePatterns: supabaseHost
      ? [{ protocol: 'https', hostname: supabaseHost, pathname: '/storage/v1/object/**' }]
      : [],
  },
  async redirects() {
    return [
      { source: '/category/:slug', destination: '/shop?category=:slug', permanent: true },
      { source: '/custom-orders', destination: '/shop?custom=1', permanent: true },
      { source: '/cart', destination: '/checkout', permanent: false },
      { source: '/faq', destination: '/contact', permanent: true },
      { source: '/shipping-returns', destination: '/contact', permanent: true },
      { source: '/privacy', destination: '/', permanent: false },
      { source: '/terms', destination: '/', permanent: false },
    ];
  },
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
        ],
      },
    ];
  },
};

export default nextConfig;
